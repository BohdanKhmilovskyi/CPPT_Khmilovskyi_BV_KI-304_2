package KI304.Khmilovskyi.Lab3;

/**
 * Інтерфейс {@code ClimateDevice} визначає набір можливостей,
 * які повинні реалізовувати розширені кліматичні пристрої.
 * <p>
 * Використовується в лабораторній роботі №3 для демонстрації
 * роботи з інтерфейсами та принципами абстракції в Java.
 *
 * Основні функції:
 * <ul>
 *     <li>встановлення цільової температури;</li>
 *     <li>активація Eco режиму;</li>
 *     <li>деактивація Eco режиму;</li>
 *     <li>планування автоматичного вимкнення;</li>
 * </ul>
 *
 * @author
 *     Bohdan Khmilovskyi, KI-304
 * @version 1.0
 */
public interface ClimateDevice {

    /**
     * Встановлює нову цільову температуру.
     *
     * @param temp значення температури
     */
    void setTargetTemperature(int temp);

    /**
     * Увімкнення Eco режиму (режим економії енергії).
     */
    void enableEcoMode();

    /**
     * Вимкнення Eco режиму.
     */
    void disableEcoMode();

    /**
     * Планує автоматичне вимкнення через зазначений час.
     * Якщо {@code minutes <= 0}, то планування очищується.
     *
     * @param minutes кількість хвилин до вимкнення
     */
    void scheduleShutdown(int minutes);
}
